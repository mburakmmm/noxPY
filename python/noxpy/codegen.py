"""Deterministic `.pyi` type stub and `abi3t` C adapter emitters from ModuleIR (`AGENTS.md` §7)."""

from __future__ import annotations

from .ir import ExportedFunctionIR, ModuleIR


def _c_escape(text: str) -> str:
    """Escape arbitrary UTF-8 text into a safe C string literal."""
    out: list[str] = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\0":
            out.append("\\000")
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(f"\\x{ord(ch):02x}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def _format_pyi_params(fn: ExportedFunctionIR) -> str:
    pos_only = [p for p in fn.params if p.kind == "positional_only"]
    pos_or_kw = [p for p in fn.params if p.kind == "positional_or_keyword"]
    kw_only = [p for p in fn.params if p.kind == "keyword_only"]

    parts: list[str] = []
    for p in pos_only:
        parts.append(f"{p.name}: {p.type_name}")
    if pos_only:
        parts.append("/")
    for p in pos_or_kw:
        parts.append(f"{p.name}: {p.type_name}")
    if kw_only:
        parts.append("*")
        for p in kw_only:
            parts.append(f"{p.name}: {p.type_name}")
    return ", ".join(parts)


def generate_pyi(ir: ModuleIR) -> str:
    """Emit deterministic PEP 561 `.pyi` stub from validated ModuleIR."""
    lines = [
        f"# Generated by noxpy from {ir.source} (noxc {ir.compiler_version}). Do not hand-edit.",
        "",
    ]
    for fn in ir.functions:
        sig = f"def {fn.name}({_format_pyi_params(fn)}) -> {fn.return_type}:"
        if fn.doc:
            escaped_doc = fn.doc.replace('"""', '\\"\\"\\"')
            lines.append(sig)
            lines.append(f'    """{escaped_doc}"""')
            lines.append("    ...")
        else:
            lines.append(f"{sig} ...")
    lines.append("")
    return "\n".join(lines)


_C_HOST_TYPE_MAP = {
    "int": "int64_t",
    "float": "double",
    "bool": "uint8_t",
    "str": "NoxHostSpan",
    "bytes": "NoxHostSpan",
    "None": "void",
}


def _emit_c_function_adapter(fn: ExportedFunctionIR) -> list[str]:
    lines: list[str] = []
    c_params = ["NoxHostContext *ctx"]
    for i, p in enumerate(fn.params):
        c_params.append(f"{_C_HOST_TYPE_MAP[p.type_name]} arg_{i}")
    if fn.return_type != "None":
        c_params.append(f"{_C_HOST_TYPE_MAP[fn.return_type]} *out_val")
    c_params.append("NoxHostError *out_err")

    lines.append(f"extern NoxHostStatus {fn.c_symbol}({', '.join(c_params)});")
    lines.append("")
    lines.append(f"static PyObject *noxpy_wrap_{fn.name}(PyObject *module, PyObject *const *args, Py_ssize_t nargs) {{")
    lines.append(f"    if (nargs != {len(fn.params)}) {{")
    lines.append(
        f'        PyErr_Format(PyExc_TypeError, "{fn.name}() takes exactly {len(fn.params)} argument(s) (%zd given)", nargs);'
    )
    lines.append("        return NULL;")
    lines.append("    }")

    for i, p in enumerate(fn.params):
        ctype = _C_HOST_TYPE_MAP[p.type_name]
        init = "{0}" if ctype == "NoxHostSpan" else "0"
        lines.append(f"    {ctype} c_arg_{i} = {init};")
        conv = {
            "int": "noxpy_py_to_i64_strict",
            "float": "noxpy_py_to_f64_strict",
            "bool": "noxpy_py_to_bool_strict",
            "str": "noxpy_py_to_utf8_span_strict",
            "bytes": "noxpy_py_to_bytes_span_strict",
        }[p.type_name]
        lines.append(f"    if ({conv}(args[{i}], &c_arg_{i}, {_c_escape(p.name)}) < 0) {{")
        lines.append("        return NULL;")
        lines.append("    }")

    lines.append("    NoxPyModuleState *st = (NoxPyModuleState *)PyModule_GetState(module);")
    lines.append("    if (!st || noxpy_module_lease_acquire(st) < 0) {")
    lines.append("        return NULL;")
    lines.append("    }")

    if fn.return_type != "None":
        ret_ctype = _C_HOST_TYPE_MAP[fn.return_type]
        ret_init = "{0}" if ret_ctype == "NoxHostSpan" else "0"
        lines.append(f"    {ret_ctype} c_ret = {ret_init};")

    call_args = ["st->host_ctx"] + [f"c_arg_{i}" for i in range(len(fn.params))]
    if fn.return_type != "None":
        call_args.append("&c_ret")
    call_args.append("&err")

    lines.append("    NoxHostError err = {0};")
    lines.append("    NoxHostStatus rc;")
    lines.append("    Py_BEGIN_ALLOW_THREADS")
    lines.append(f"    rc = {fn.c_symbol}({', '.join(call_args)});")
    lines.append("    Py_END_ALLOW_THREADS")
    lines.append("    noxpy_module_lease_release(st);")
    lines.append("    if (rc != NOX_HOST_OK) {")
    lines.append("        noxpy_set_exception_from_host(rc, &err);")
    lines.append("        if (st->runtime_ops && st->runtime_ops->error_clear) {")
    lines.append("            st->runtime_ops->error_clear(&err);")
    lines.append("        }")
    lines.append("        return NULL;")
    lines.append("    }")

    if fn.return_type == "None":
        lines.append("    Py_RETURN_NONE;")
    else:
        ret_conv = {
            "int": "noxpy_i64_to_py",
            "float": "noxpy_f64_to_py",
            "bool": "noxpy_bool_to_py",
            "str": "noxpy_utf8_span_to_py",
            "bytes": "noxpy_bytes_span_to_py",
        }[fn.return_type]
        lines.append(f"    return {ret_conv}(c_ret);")
    lines.append("}")
    lines.append("")
    return lines


def generate_c_adapter(ir: ModuleIR) -> str:
    """Emit deterministic CPython 3.15 `abi3t` C adapter targeting `nox_host_abi.h`."""
    leaf = ir.leaf_name
    lines: list[str] = [
        f"/* Generated by noxpy from {ir.source} (noxc {ir.compiler_version}). Do not hand-edit. */",
        '#include "noxpy_abi.h"',
        "",
        "extern const NoxHostRuntimeOps *nox_host_runtime_ops_v1(void);",
        "",
    ]

    for fn in ir.functions:
        lines.extend(_emit_c_function_adapter(fn))

    lines.append(f"static PyMethodDef noxpy_methods_{leaf}[] = {{")
    for fn in ir.functions:
        doc_c = _c_escape(fn.doc) if fn.doc else "NULL"
        lines.append(
            f"    {{ {_c_escape(fn.name)}, _PyCFunction_CAST(noxpy_wrap_{fn.name}), METH_FASTCALL, {doc_c} }},"
        )
    lines.append("    { NULL, NULL, 0, NULL }")
    lines.append("};")
    lines.append("")
    lines.extend(
        [
            f"static int noxpy_exec_{leaf}(PyObject *module) {{",
            "    NoxPyModuleState *st = (NoxPyModuleState *)PyModule_GetState(module);",
            "    if (!st) {",
            '        PyErr_SetString(PyExc_RuntimeError, "noxpy: missing module state");',
            "        return -1;",
            "    }",
            "    return noxpy_module_state_init(st, nox_host_runtime_ops_v1());",
            "}",
            "",
            f"static void noxpy_free_{leaf}(void *module) {{",
            "    NoxPyModuleState *st = (NoxPyModuleState *)PyModule_GetState((PyObject *)module);",
            "    if (st) {",
            "        noxpy_module_state_close(st);",
            "    }",
            "}",
            "",
            f"PyABIInfo_VAR(noxpy_abi_info_{leaf});",
            "",
            f"static PySlot noxpy_slots_{leaf}[] = {{",
            f"    PySlot_STATIC_DATA(Py_mod_abi, &noxpy_abi_info_{leaf}),",
            f"    PySlot_STATIC_DATA(Py_mod_name, {_c_escape(leaf)}),",
            "    PySlot_SIZE(Py_mod_state_size, sizeof(NoxPyModuleState)),",
            f"    PySlot_STATIC_DATA(Py_mod_methods, noxpy_methods_{leaf}),",
            f"    PySlot_FUNC(Py_mod_exec, noxpy_exec_{leaf}),",
            f"    PySlot_FUNC(Py_mod_state_free, noxpy_free_{leaf}),",
            "    PySlot_DATA(Py_mod_gil, Py_MOD_GIL_NOT_USED),",
            "    PySlot_DATA(Py_mod_multiple_interpreters, Py_MOD_MULTIPLE_INTERPRETERS_NOT_SUPPORTED),",
            "    PySlot_END",
            "};",
            "",
            "PyMODEXPORT_FUNC",
            f"PyModExport_{leaf}(void) {{",
            f"    return noxpy_slots_{leaf};",
            "}",
            "",
        ]
    )
    return "\n".join(lines)
